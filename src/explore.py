"""Profile the 50 company records and pick an evaluation sample.

Run:  uv run python src/explore.py
Writes:
  eval/data_profile.md  - dataset-level counts (what varies across companies)
  eval/companies_overview.csv - one row of key facts per company
  eval/sample.md        - the ~12 companies chosen for the gold set, and why
"""

import json
from datetime import date
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "companies.jsonl"
OUT = ROOT / "eval"
AS_OF = date(2025, 12, 31)  # records are as of this date (README)


def load() -> list[dict]:
    return [json.loads(line) for line in DATA.read_text(encoding="utf-8").splitlines() if line.strip()]


def overview_row(r: dict) -> dict:
    p, rel = r["profile"], r["relationships"]
    years = r["financials"]["years"]
    cases = r["litigation"]["cases"]
    latest = years[-1] if years else None
    first = years[0] if years else None
    st = latest["statements"] if latest else {}

    pending_def = [c for c in cases if c["role"] == "defendant" and c["status"] == "Pending"]
    corp_holders = [s for s in rel["shareholders"] if s["type"] == "company"]
    recent_directors = [d for d in rel["directors"] if d["appointedOn"] >= "2025-01-01"]

    rev_growth = None
    if first and latest and first is not latest and first["statements"]["revenue"]:
        rev_growth = latest["statements"]["revenue"] / first["statements"]["revenue"] - 1

    return {
        "registrationNumber": r["registrationNumber"],
        "companyName": p["companyName"],
        "industry": p["industry"],
        "status": p["status"],
        "ageYears": round((AS_OF - date.fromisoformat(p["incorporationDate"])).days / 365.25, 1),
        "formerNames": len(p["formerNames"]),
        "nYears": len(years),
        "latestFY": latest["financialYear"] if latest else None,
        "latestFYEnd": latest["financialYearEnd"] if latest else None,
        "badAuditOpinion": any(y["audit"]["opinion"] != "Unqualified" for y in years),
        "auditOpinions": "; ".join(sorted({y["audit"]["opinion"] for y in years})),
        "latestRevenue": st.get("revenue"),
        "revenueGrowthFirstToLatest": rev_growth,
        "latestProfitAfterTax": st.get("profitAfterTax"),
        "lossYears": sum(y["statements"]["profitAfterTax"] < 0 for y in years),
        "latestEquity": st.get("totalEquity"),
        "negativeEquity": st.get("totalEquity", 0) < 0,
        "latestOperatingCashFlow": st.get("operatingCashFlow"),
        "nCases": len(cases),
        "nDefendant": sum(c["role"] == "defendant" for c in cases),
        "nPendingDefendant": len(pending_def),
        "pendingDefendantClaimRM": sum(c["claimAmount"] for c in pending_def),
        "windingUpPetitions": sum(c["caseType"] == "Winding-up petition" for c in cases),
        "nDirectors": len(rel["directors"]),
        "directorsAppointed2025": len(recent_directors),
        "nShareholders": len(rel["shareholders"]),
        "topShareholderPct": max((s["percentage"] for s in rel["shareholders"]), default=None),
        "corporateShareholders": len(corp_holders),
    }


def write_profile(df: pd.DataFrame) -> None:
    n = len(df)
    lines = [
        "# Data profile (all 50 companies)",
        "",
        "Generated by `src/explore.py`. Records are as of 31 Dec 2025.",
        "",
        "| What | Companies |",
        "|---|---|",
        f"| Status not Active | {(df.status != 'Active').sum()} of {n} ({', '.join(df.status.unique())}) |",
        f"| No financial years | {(df.nYears == 0).sum()} |",
        f"| 1 or 2 financial years only | {df.nYears.between(1, 2).sum()} |",
        f"| Latest financial year | {', '.join(f'FY{k}: {v}' for k, v in df.latestFY.value_counts().items())} (accounts are 12+ months old) |",
        f"| Any non-clean audit opinion | {df.badAuditOpinion.sum()} |",
        f"| Loss in latest year | {(df.latestProfitAfterTax < 0).sum()} |",
        f"| Loss in every year filed | {((df.lossYears == df.nYears) & (df.nYears > 0)).sum()} |",
        f"| Negative equity (latest) | {df.negativeEquity.sum()} |",
        f"| Negative operating cash flow (latest) | {(df.latestOperatingCashFlow < 0).sum()} |",
        f"| Any court case | {(df.nCases > 0).sum()} ({df.nCases.sum()} cases in total) |",
        f"| Pending case as defendant | {(df.nPendingDefendant > 0).sum()} |",
        f"| Winding-up petition filed | {(df.windingUpPetitions > 0).sum()} |",
        f"| Director appointed in 2025 | {(df.directorsAppointed2025 > 0).sum()} |",
        f"| Corporate shareholder | {(df.corporateShareholders > 0).sum()} |",
        f"| Former names | {(df.formerNames > 0).sum()} |",
        f"| Top shareholder holds > 50% | {(df.topShareholderPct > 50).sum()} |",
        "",
        "Industries: " + ", ".join(f"{k} {v}" for k, v in df.industry.value_counts().items()),
        "",
    ]
    (OUT / "data_profile.md").write_text("\n".join(lines), encoding="utf-8")


# Each rule picks companies for one kind of risk. Order matters: earlier rules pick first.
SAMPLE_RULES: list[tuple[str, str, int]] = [
    ("Status is winding up", "status != 'Active'", 2),
    ("No financial statements filed", "nYears == 0", 2),
    ("Non-clean audit opinion", "badAuditOpinion", 3),
    ("Winding-up petition against it", "windingUpPetitions > 0 and status == 'Active'", 1),
    ("Heavy litigation, pending as defendant", "nPendingDefendant >= 2", 1),
    ("Negative equity", "negativeEquity", 1),
    ("Losses in latest year", "latestProfitAfterTax < 0", 1),
    ("Corporate shareholder / former names", "corporateShareholders > 0 or formerNames > 0", 1),
]


def pick_sample(df: pd.DataFrame) -> pd.DataFrame:
    picked: dict[str, str] = {}
    for reason, query, k in SAMPLE_RULES:
        pool = df.query(query)
        pool = pool[~pool.registrationNumber.isin(picked)]
        for reg in pool.sort_values("nCases", ascending=False).registrationNumber.head(k):
            picked[reg] = reason
    # Clean controls: active, 3 years, clean audits, profitable, no cases. The system must not invent risk.
    clean = df.query(
        "status == 'Active' and nYears == 3 and not badAuditOpinion and lossYears == 0 and nCases == 0 and not negativeEquity"
    )
    for reg in clean[~clean.registrationNumber.isin(picked)].registrationNumber.head(2):
        picked[reg] = "Clean control (no obvious risk)"
    out = df[df.registrationNumber.isin(picked)].copy()
    out["whyPicked"] = out.registrationNumber.map(picked)
    return out


def write_sample(sample: pd.DataFrame) -> None:
    cols = ["registrationNumber", "companyName", "industry", "whyPicked", "status", "nYears", "auditOpinions",
            "latestProfitAfterTax", "nCases", "nPendingDefendant", "windingUpPetitions"]
    sample = sample.copy()
    sample["latestProfitAfterTax"] = sample.latestProfitAfterTax.map(lambda v: "-" if pd.isna(v) else f"{v:,.0f}")
    lines = [
        "# Evaluation sample",
        "",
        f"{len(sample)} companies picked by `src/explore.py` so that every kind of risk in the data appears at least",
        "once, plus clean controls. A summary system must both catch real red flags and not invent them.",
        "",
        sample[cols].to_markdown(index=False),
        "",
    ]
    (OUT / "sample.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    OUT.mkdir(exist_ok=True)
    df = pd.DataFrame([overview_row(r) for r in load()])
    df["latestFY"] = df.latestFY.astype("Int64")
    df.to_csv(OUT / "companies_overview.csv", index=False)
    write_profile(df)
    sample = pick_sample(df)
    write_sample(sample)
    print((OUT / "data_profile.md").read_text(encoding="utf-8"))
    print((OUT / "sample.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
